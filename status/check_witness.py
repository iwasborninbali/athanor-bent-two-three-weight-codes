#!/usr/bin/env python3
"""Independent, field-free checker: only GF(3) vector arithmetic + witness JSON.
Does not import the field implementation and does not trust its histograms,
dimensions, reported basis or minimality flag.
"""
from collections import Counter
from itertools import product
from pathlib import Path
import json

def plus(a,b):
    return tuple((i+j)%3 for i,j in zip(a,b))

def times(s,a):
    return tuple(s*i%3 for i in a)

def is_multiple(a,b):
    return any(a==times(k,b) for k in (1,2))

def supp(a):
    return {k for k,x in enumerate(a) if x}

def main():
    data=json.loads(Path(__file__).with_name('witness.json').read_text())
    for case in data['cases']:
        m,n=case['dimension'],case['length']
        W=[tuple(v) for v in case['words']]
        assert len(W)==3**m and len(set(W))==3**m
        assert all(len(v)==n and all(x in (0,1,2) for x in v) for v in W)
        assert len(case['D'])==n and len(set(tuple(v) for v in case['D']))==n
        z=(0,)*n
        assert W.count(z)==1
        # Independent linear span generated by the reported basis words.
        B=[W[i] for i in case['basis_word_indices']]
        span={z}
        for b in B:
            span={plus(x,times(j,b)) for x in span for j in range(3)}
        assert span==set(W)
        # Independent closure test of the *full* enumerated code, not just its basis.
        assert all(plus(a,b) in span for a in W for b in W)
        hist=dict(sorted(Counter(sum(x!=0 for x in w) for w in W).items()))
        reported={int(k):v for k,v in case['weight_multiplicities'].items()}
        assert hist==reported
        violations=[]
        for i,a in enumerate(W):
            if a==z: continue
            for j,b in enumerate(W):
                if b==z: continue
                if supp(b).issubset(supp(a)) and not is_multiple(a,b):
                    violations.append((i,j))
        observed_min=(len(violations)==0)
        assert observed_min==case['minimality']['minimal']
        if not observed_min:
            d=case['minimality']
            i,j=d['containing_index'],d['contained_index']
            assert (i,j) in violations
            assert list(W[i])==d['containing_word'] and list(W[j])==d['contained_word']
        if (case['m'],case['level'])==(3,0):
            assert hist=={0:1,4:12,6:8,8:6}, hist
        if (case['m'],case['level'])==(4,0):
            assert hist=={0:1,12:60,18:20}, hist
        print(f"PASS GF(3^{case['m']}) level={case['level']} "
              f"n={n} dimension={m} histogram={hist} "
              f"minimal={observed_min} nonproportional inclusions={len(violations)}")
    print("PASS: all cases cross-checked; enumerated spans, dimensions, counts, and support containment.")

if __name__=='__main__': main()
